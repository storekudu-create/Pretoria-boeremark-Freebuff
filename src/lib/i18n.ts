const DICTS: Record<Lang, Dict> = { en, af };

export function detectLang(): Lang {
  try {
    const stored = localStorage.getItem('bm_lang');
    if (stored === 'af' || stored === 'en') return stored;
  } catch { /* ignore */ }
  if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('af')) return 'af';
  return 'en';
}

export function translate(lang: Lang, key: string): string {
  return DICTS[lang][key] ?? DICTS.en[key] ?? key;
}
